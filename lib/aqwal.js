/** Same saying for everyone on a given day (Pakistan time). */
export function sayingOfTheDay(date = new Date()) {
  const all = AQWAL_SECTIONS.filter((s) => s.key !== "proverbs").flatMap((s) => s.items.map((it) => ({ ...it, section: s.key })));
  const dayIndex = Math.floor((date.getTime() + 5 * 3600e3) / 86400e3);
  return all[(dayIndex * 7) % all.length];
}
