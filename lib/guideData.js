export function guideBody(g, lang) {
  const t = g[lang];
  const rows = g.rows.map((r) => `- **${r.n}** — ${r[lang]}`).join("\n");
  const src = g.sources.map(([n, u]) => `- [${n}](${u})`).join("\n");
  const note = g.note ? `\n\n${g.note[lang]}` : "";
  const head = lang === "ur" ? "ماخذ" : "Sources";
  const chk = lang === "ur" ? `آخری بار تصدیق: ${CHECKED}` : `Last checked: ${CHECKED}`;
  return `${t.summary}\n\n${rows}${note}\n\n**${head}**\n\n${src}\n\n_${chk}_`;
}
