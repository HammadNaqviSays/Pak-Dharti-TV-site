export const findPoet = (slug) => POETS.find((p) => p.slug === slug);
export const findPoem = (poet, slug) => poet?.poems.find((p) => p.slug === slug);

/** Same couplet for everyone on a given day (Pakistan time). */
export function verseOfTheDay(date = new Date()) {
  const all = POETS.flatMap((poet) => poet.poems.map((poem) => ({ poet, poem })));
  const pk = new Date(date.getTime() + 5 * 3600e3);
  const dayIndex = Math.floor(pk.getTime() / 86400e3);
  return all[dayIndex % all.length];
}
